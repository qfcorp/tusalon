<h1>Política de privacidad de TuSalón</h1>
<p><small>Última actualización: 12 de octubre de 2026</small></p>

<p>TuSalón es un sistema de agenda, caja y clientes para peluquerías y barberías, hecho por <b>Tukán Software</b> (QF Producciones, Ecuador). Esta política explica qué datos guarda TuSalón, para qué y cómo puedes pedir que se borren. Se aplica a la página <b>tusalon.tukanec.com</b> y a la app de Android.</p>

<h2>Quién es el responsable</h2>
<ul>
<li><b>Cada salón</b> es el responsable de los datos de sus clientes y de su equipo. TuSalón los guarda por cuenta del salón.</li>
<li><b>Tukán Software</b> es responsable de los datos de la cuenta del salón (dueño, plan y pagos del plan).</li>
<li>Contacto: <a href="mailto:info@tukansoftware.com">info@tukansoftware.com</a> · WhatsApp 099 640 8397.</li>
</ul>

<h2>Qué datos guardamos</h2>
<ul>
<li><b>Del dueño y su equipo:</b> nombre, correo, teléfono, contraseña (cifrada), horarios y comisiones.</li>
<li><b>De los clientes del salón:</b> nombre, teléfono, correo si lo dan, citas, servicios, pagos, puntos, paquetes, tarjetas de regalo y, si el salón lo usa, la ficha técnica (fórmula de color) y fotos del trabajo. Las fotos de la ficha solo se toman con autorización del cliente.</li>
<li><b>Pagos:</b> montos y forma de pago. Los pagos con tarjeta los procesa <b>Payphone</b> y los de la app los procesa <b>Google Play</b>: TuSalón <b>no</b> guarda números de tarjeta. Si se sube un comprobante de transferencia, se guarda la imagen.</li>
<li><b>Avisos:</b> si alguien conecta Telegram, se guarda su número de chat para enviarle avisos de citas.</li>
<li><b>Datos técnicos:</b> una cookie de sesión para mantenerte dentro y registros básicos del servidor (fecha, dirección IP) para seguridad.</li>
</ul>

<h2>Para qué los usamos</h2>
<ul>
<li>Para que el salón pueda agendar, cobrar, llevar sus cuentas y avisar a sus clientes.</li>
<li>Para cobrar y renovar el plan de TuSalón.</li>
<li>No vendemos datos, no mostramos publicidad y no usamos los datos para otra cosa.</li>
</ul>

<h2>Con quién se comparten</h2>
<ul>
<li>Solo con los servicios necesarios para que funcione: el servidor y la red de Cloudflare, Payphone (pagos con tarjeta), Google Play (pago del plan en la app) y Telegram (avisos, solo si se activa).</li>
<li>Con autoridades, solo si la ley lo exige.</li>
</ul>

<h2>Cuánto tiempo se guardan</h2>
<p>Mientras la cuenta del salón esté activa. Si el salón deja TuSalón, sus datos se borran a los 90 días, salvo lo que la ley obligue a guardar (por ejemplo, registros de pagos).</p>

<h2>Tus derechos y cómo borrar tu cuenta</h2>
<p>Según la Ley Orgánica de Protección de Datos Personales del Ecuador, puedes pedir ver, corregir o borrar tus datos.</p>
<ul>
<li><b>Dueño de un salón:</b> para borrar la cuenta y todos sus datos, escribe desde el correo de la cuenta a <a href="mailto:info@tukansoftware.com?subject=Borrar%20mi%20cuenta%20de%20TuSal%C3%B3n">info@tukansoftware.com</a> con el asunto "Borrar mi cuenta de TuSalón". Lo hacemos en un máximo de 15 días y te avisamos.</li>
<li><b>Cliente de un salón:</b> pide al salón que borre tus datos, o escríbenos al mismo correo indicando el salón y tu teléfono.</li>
<li><b>Miembro del equipo:</b> pide al dueño que te desactive, o escríbenos.</li>
</ul>

<h2>Seguridad</h2>
<p>La conexión va cifrada (HTTPS), las contraseñas se guardan cifradas y cada salón solo ve sus propios datos.</p>

<h2>Menores de edad</h2>
<p>TuSalón es para negocios. No está dirigido a menores de edad.</p>

<h2>Cambios</h2>
<p>Si cambiamos esta política, publicaremos la nueva versión aquí con su fecha.</p>
